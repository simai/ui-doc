def readable_css_files(asset_root: Path) -> list[Path]:
    return sorted(
        path
        for path in asset_root.rglob("*.css")
        if ".min." not in path.name and not path.name.endswith(".css.gz")
    )


def component_css_contract(ui_root: Path, entry: dict[str, Any]) -> tuple[list[str], list[str]]:
    root = ui_root / entry["runtime"]["asset_root"]
    selectors: set[str] = set()
    variables: set[str] = set()
    for path in readable_css_files(root):
        text = path.read_text(encoding="utf-8", errors="replace")
        selectors.update(re.findall(r"\.sf-[a-z0-9_-]+", text))
        variables.update(re.findall(r"--sf-[a-z0-9_-]+", text))
    return sorted(selectors)[:40], sorted(variables)[:60]



def markdown_link_for_doc(path: Path) -> str:
    if path.stem == path.parent.name:
        path = path.parent
    relative = path.relative_to(DOCS_ROOT).with_suffix("")
    value = relative.as_posix()
    if value.endswith("/index"):
        value = value[:-6]
    return "/ru/" + value.rstrip("/") + "/"


def utility_authored_map() -> dict[str, Path]:
    result: dict[str, Path] = {}
    pattern = re.compile(r"!rtags\[([^\]]+)\]")
    for path in sorted((DOCS_ROOT / "utilities").rglob("*.md")):
        if "/reference/" in path.as_posix():
            continue
        text = path.read_text(encoding="utf-8")
        for match in pattern.finditer(text):
            tokens = match.group(1).split()
            if tokens:
                result.setdefault(tokens[0], path)
    return result


def table_row(values: list[str]) -> str:
    return "| " + " | ".join(value.replace("\n", " ") for value in values) + " |"



def reference_index(kind: str, entries: list[dict[str, Any]]) -> str:
    smart = kind == "smart-component"
    section = "Smart Components" if smart else "компонентов"
    title = "Справочник Smart Components" if smart else "Справочник компонентов"
    description = f"Полный source-backed справочник {section} SIMAI Framework 5.4.0 candidate."
    lines = [page_header(title, description), f"# {title}\n", "Страницы ниже сгенерированы из закреплённого owner registry. Они фиксируют поставку, Loader-координаты, зависимости и наблюдаемый API без предположений о незакреплённой release-версии.\n", f"Всего записей: **{len(entries)}**.\n", "| Имя | Статус | Жизненный цикл | Loader |", "|:---|:---|:---|:---|"]

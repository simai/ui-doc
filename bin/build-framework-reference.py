def find_matching(text: str, start: int, opening: str = "{", closing: str = "}") -> int:
    depth = 0
    quote = ""
    escaped = False
    for index in range(start, len(text)):
        char = text[index]
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = ""
            continue
        if char in {'"', "'", "`"}:
            quote = char
        elif char == opening:
            depth += 1
        elif char == closing:
            depth -= 1
            if depth == 0:
                return index
    return -1


def top_level_items(body: str) -> list[tuple[str, str]]:
    result: list[tuple[str, str]] = []
    index = 0
    key_pattern = re.compile(r"\s*([A-Za-z_$][\w$]*)\s*:\s*")
    while index < len(body):
        match = key_pattern.match(body, index)
        if not match:
            index += 1
            continue
        key = match.group(1)
        value_start = match.end()
        depth = 0
        quote = ""
        escaped = False
        cursor = value_start
        while cursor < len(body):
            char = body[cursor]
            if quote:
                if escaped:
                    escaped = False
                elif char == "\\":
                    escaped = True
                elif char == quote:
                    quote = ""
            elif char in {'"', "'", "`"}:
                quote = char
            elif char in "{[(":
                depth += 1
            elif char in "}])":
                depth -= 1
            elif char == "," and depth == 0:
                break
            cursor += 1
        result.append((key, body[value_start:cursor].strip()))
        index = cursor + 1
    return result


def compact_js(value: str, fallback: str = "—") -> str:
    normalized = re.sub(r"\s+", " ", value.strip()).replace("|", "\\|")
    return normalized[:120] if normalized else fallback


def smart_props(text: str) -> list[SmartProp]:
    blocks: list[str] = []
    for match in re.finditer(r"static\s+get\s+props\s*\(\)\s*\{", text):
        end = find_matching(text, text.find("{", match.start()))
        if end < 0:
            continue
        block = text[match.end():end]
        returned = re.search(r"return\s*\{", block)
        if not returned:
            continue
        start = block.find("{", returned.start())
        object_end = find_matching(block, start)
        if object_end >= 0:
            blocks.append(block[start + 1:object_end])
    if not blocks:
        return []
    props: list[SmartProp] = []
    for prop, value in top_level_items(blocks[-1]):
        attribute = re.search(r"\battribute\s*:\s*['\"]([^'\"]+)['\"]", value)
        if re.search(r"\battribute\s*:\s*false", value):
            continue
        attr = attribute.group(1) if attribute else re.sub(r"([A-Z])", r"-\1", prop).lower()
        type_match = re.search(r"\btype\s*:\s*([A-Za-z_$][\w$]*)", value)
        default_match = re.search(r"\bdefault\s*:\s*([^,}]+)", value)
        values_match = re.search(r"\bvalues\s*:\s*(\[[^\]]*\])", value)
        if value.startswith("{"):
            type_name = type_match.group(1) if type_match else "String"
            default = compact_js(default_match.group(1)) if default_match else "—"
        else:
            literal = compact_js(value)
            default = literal
            type_name = "Boolean" if literal in {"true", "false"} else "Number" if re.fullmatch(r"-?\d+(?:\.\d+)?", literal) else "String"
        props.append(
            SmartProp(
                attribute=attr,
                prop=prop,
                type_name=type_name,
                default=default,
                values=compact_js(values_match.group(1)) if values_match else "—",
            )
        )
    return props


def smart_methods_and_events(text: str) -> tuple[list[str], list[str]]:
    classes = list(re.finditer(r"class\s+(Sf[A-Za-z0-9_$]+)\s+extends", text))
    if not classes:
        return [], []
    start = classes[-1].start()
    define = text.find(".define(", start)
    segment = text[start:define if define >= 0 else len(text)]
    methods: set[str] = set()
    for match in re.finditer(r"^\s{2}(?:async\s+)?(?:(get|set)\s+)?([A-Za-z_$][\w$]*)\s*\(", segment, re.M):
        kind, name = match.groups()
        if name == "constructor" or name.startswith("_"):
            continue
        label = f"{kind} {name}" if kind else name
        methods.add(label)
    events = {
        f"sf-{name}"
        for name in re.findall(r"emitComponentEvent\(\s*['\"]([^'\"]+)['\"]", segment)
    }
    return sorted(methods), sorted(events)


def smart_source_file(smart_root: Path, entry: dict[str, Any]) -> Path | None:
    candidates = sorted((smart_root / "smart" / entry["name"] / "js").glob("*.js"))
    candidates = [path for path in candidates if ".min." not in path.name]
    return candidates[0] if candidates else None



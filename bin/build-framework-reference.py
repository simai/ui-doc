def validate_pointer(registry_path: Path, registry: dict[str, Any]) -> None:
    pointer = load_json(POINTER)
    if pointer.get("compatibility_id") != registry.get("compatibility", {}).get("id"):
        raise ReferenceError("consumer_pointer_compatibility_mismatch")
    expected_hash = pointer.get("registry", {}).get("file_sha256")
    if expected_hash != sha256(registry_path):
        raise ReferenceError("consumer_pointer_registry_hash_mismatch")


def write_or_check(files: dict[Path, str], check: bool) -> None:
    mismatches: list[str] = []
    for path, content in sorted(files.items()):
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                mismatches.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if mismatches:
        raise ReferenceError("generated_reference_drift:" + ",".join(mismatches))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--ui-root", type=Path, required=True)
    parser.add_argument("--smart-root", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    registry_path = args.registry.resolve()
    registry = load_json(registry_path)
    validate_pointer(registry_path, registry)
    files = expected_files(registry, args.ui_root.resolve(), args.smart_root.resolve())
    write_or_check(files, args.check)
    print(f"framework reference: PASS ({len(files)} files)")
    return 0


